// Time zones for std/time's DateTime: each value can be in its own zone,
// so zones are loaded here rather than through musl's single global one.
// A zone comes from the system's zoneinfo files (TZif, RFC 8536) when it has
// them, which the system keeps up to date, or else from the copy of the tz
// database embedded in qiq (vendor/tzdata.bin, made by
// vendor/make_tzdata.py), so programs in minimal containers still know
// their zones. "UTC" and fixed offsets such as "+05:30" need neither.
//
// A zone is a list of transitions, each to a type (a UTC offset, whether
// it's daylight saving time, and an abbreviation), and a POSIX TZ rule for
// the times after the last one, such as "CET-1CEST,M3.5.0,M10.5.0/3".
#define _DEFAULT_SOURCE
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>

#include "qiq_runtime.h"
#include "tzdata.h" // qiq_tzdata, generated by build.rs from vendor/tzdata.bin

typedef struct {
    int32_t offset;           // seconds east of UTC
    bool dst;
    char abbreviation[16];
} QiqZoneType;

// A POSIX rule's date: Mm.w.d (the d'th day of the week, 0 Sunday, in week w,
// 5 the last, of month m), Jn (day n of 365, never February 29), or n (day n
// from 0, counting February 29).
typedef struct {
    char kind;                // 'M', 'J', or 'N'
    int month, week, weekday, day;
    int32_t time;             // seconds after local midnight (may be negative or past 24h)
} QiqRuleDate;

typedef struct {
    bool present;
    QiqZoneType standard, daylight;
    bool has_daylight;
    QiqRuleDate start, end;
} QiqRule;

struct QiqZone {
    char *name;
    int64_t *times;           // transitions, ascending
    uint8_t *indexes;         // the type each transition changes to
    size_t count;
    QiqZoneType *types;
    size_t type_count;
    size_t initial;           // the type before the first transition
    QiqRule rule;             // for times after the last transition
    struct QiqZone *next;     // the loaded zones
};

static QiqZone *qiq_zones;

// ---------------------------------------------------------------------------
// POSIX TZ rules

static bool qiq_rule_name(const char **cursor, char *out, size_t size) {
    const char *c = *cursor;
    size_t length = 0;
    if (*c == '<') {
        c++;
        while (*c != '\0' && *c != '>') {
            if (length + 1 < size) out[length++] = *c;
            c++;
        }
        if (*c != '>') return false;
        c++;
    } else {
        while ((*c >= 'a' && *c <= 'z') || (*c >= 'A' && *c <= 'Z')) {
            if (length + 1 < size) out[length++] = *c;
            c++;
        }
        if (length < 3) return false;
    }
    out[length] = '\0';
    *cursor = c;
    return true;
}

// [+-]hh[:mm[:ss]], in seconds.
static bool qiq_rule_time(const char **cursor, int32_t *out) {
    const char *c = *cursor;
    int sign = 1;
    if (*c == '+' || *c == '-') sign = *c++ == '-' ? -1 : 1;
    int32_t parts[3] = {0, 0, 0};
    for (int part = 0; part < 3; part++) {
        if (*c < '0' || *c > '9') return false;
        int32_t value = 0;
        while (*c >= '0' && *c <= '9') value = value * 10 + (*c++ - '0');
        parts[part] = value;
        if (*c != ':') break;
        c++;
    }
    *out = sign * (parts[0] * 3600 + parts[1] * 60 + parts[2]);
    *cursor = c;
    return true;
}

static int qiq_rule_number(const char **cursor) {
    int value = 0;
    while (**cursor >= '0' && **cursor <= '9') value = value * 10 + (*(*cursor)++ - '0');
    return value;
}

static bool qiq_rule_date(const char **cursor, QiqRuleDate *out) {
    const char *c = *cursor;
    if (*c++ != ',') return false;
    if (*c == 'M') {
        c++;
        out->kind = 'M';
        out->month = qiq_rule_number(&c);
        if (*c++ != '.') return false;
        out->week = qiq_rule_number(&c);
        if (*c++ != '.') return false;
        out->weekday = qiq_rule_number(&c);
        if (out->month < 1 || out->month > 12 || out->week < 1 || out->week > 5 || out->weekday > 6) return false;
    } else if (*c == 'J') {
        c++;
        out->kind = 'J';
        out->day = qiq_rule_number(&c);
    } else if (*c >= '0' && *c <= '9') {
        out->kind = 'N';
        out->day = qiq_rule_number(&c);
    } else {
        return false;
    }
    out->time = 7200;
    if (*c == '/') {
        c++;
        if (!qiq_rule_time(&c, &out->time)) return false;
    }
    *cursor = c;
    return true;
}

static bool qiq_parse_rule(const char *text, QiqRule *rule) {
    memset(rule, 0, sizeof *rule);
    if (text == NULL || *text == '\0') return false;
    const char *c = text;
    int32_t offset;
    if (!qiq_rule_name(&c, rule->standard.abbreviation, sizeof rule->standard.abbreviation) || !qiq_rule_time(&c, &offset)) return false;
    rule->standard.offset = -offset; // POSIX offsets count west of UTC
    rule->present = true;
    if (*c == '\0') return true;
    if (!qiq_rule_name(&c, rule->daylight.abbreviation, sizeof rule->daylight.abbreviation)) return false;
    rule->has_daylight = true;
    rule->daylight.dst = true;
    rule->daylight.offset = rule->standard.offset + 3600;
    if (*c != ',' && *c != '\0') {
        if (!qiq_rule_time(&c, &offset)) return false;
        rule->daylight.offset = -offset;
    }
    if (*c == '\0') {
        // No dates: the US rules, as POSIX says.
        rule->start = (QiqRuleDate){'M', 3, 2, 0, 0, 7200};
        rule->end = (QiqRuleDate){'M', 11, 1, 0, 0, 7200};
        return true;
    }
    return qiq_rule_date(&c, &rule->start) && qiq_rule_date(&c, &rule->end) && *c == '\0';
}

static int64_t qiq_floor_divide(int64_t a, int64_t b) {
    return a / b - (a % b != 0 && (a < 0) != (b < 0));
}

// Days since 1970-01-01 of a date (Howard Hinnant's days_from_civil).
static int64_t qiq_days_from_civil(int64_t year, int month, int day) {
    year -= month <= 2;
    int64_t era = qiq_floor_divide(year, 400);
    int64_t year_of_era = year - era * 400;
    int64_t day_of_year = (153 * (month + (month > 2 ? -3 : 9)) + 2) / 5 + day - 1;
    int64_t day_of_era = year_of_era * 365 + year_of_era / 4 - year_of_era / 100 + day_of_year;
    return era * 146097 + day_of_era - 719468;
}

static int64_t qiq_year_of_day(int64_t days) {
    int64_t year = qiq_floor_divide(days * 400, 146097) + 1970;
    while (qiq_days_from_civil(year, 1, 1) > days) year--;
    while (qiq_days_from_civil(year + 1, 1, 1) <= days) year++;
    return year;
}

static bool qiq_leap_year(int64_t year) {
    return (year % 4 == 0 && year % 100 != 0) || year % 400 == 0;
}

// The day (since 1970) a rule date falls on in `year`.
static int64_t qiq_rule_day(const QiqRuleDate *date, int64_t year) {
    int64_t first = qiq_days_from_civil(year, 1, 1);
    if (date->kind == 'J') return first + date->day - 1 + (qiq_leap_year(year) && date->day >= 60);
    if (date->kind == 'N') return first + date->day;
    static const int lengths[] = {31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31};
    int64_t month_start = qiq_days_from_civil(year, date->month, 1);
    int month_length = lengths[date->month - 1] + (date->month == 2 && qiq_leap_year(year));
    int64_t weekday = ((month_start + 4) % 7 + 7) % 7; // 1970-01-01 was a Thursday
    int64_t day = month_start + ((date->weekday - weekday) % 7 + 7) % 7 + (date->week - 1) * 7;
    while (day >= month_start + month_length) day -= 7;
    return day;
}

static const QiqZoneType *qiq_rule_at(const QiqRule *rule, int64_t when) {
    if (!rule->has_daylight) return &rule->standard;
    int64_t year = qiq_year_of_day(qiq_floor_divide(when + rule->standard.offset, 86400));
    int64_t start = qiq_rule_day(&rule->start, year) * 86400 + rule->start.time - rule->standard.offset;
    int64_t end = qiq_rule_day(&rule->end, year) * 86400 + rule->end.time - rule->daylight.offset;
    bool daylight = start < end ? (when >= start && when < end) : !(when >= end && when < start);
    return daylight ? &rule->daylight : &rule->standard;
}

// ---------------------------------------------------------------------------
// Loading zones

static QiqZone *qiq_new_zone(const char *name) {
    QiqZone *zone = calloc(1, sizeof *zone);
    if (zone == NULL) qiq_fatal("out of memory");
    zone->name = strdup(name);
    if (zone->name == NULL) qiq_fatal("out of memory");
    return zone;
}

static void qiq_free_zone(QiqZone *zone) {
    free(zone->name);
    free(zone->times);
    free(zone->indexes);
    free(zone->types);
    free(zone);
}

static void *qiq_zone_alloc(size_t count, size_t size) {
    void *memory = calloc(count > 0 ? count : 1, size);
    if (memory == NULL) qiq_fatal("out of memory");
    return memory;
}

static int64_t qiq_be(const unsigned char *bytes, int size) {
    uint64_t value = 0;
    for (int i = 0; i < size; i++) value = value << 8 | bytes[i];
    if (size == 4) return (int32_t)(uint32_t)value;
    return (int64_t)value;
}

// A TZif file's data, or false when it isn't one.
static bool qiq_load_tzif(QiqZone *zone, const unsigned char *data, size_t length) {
    if (length < 44 || memcmp(data, "TZif", 4) != 0) return false;
    const unsigned char *at = data;
    int size = 4;
    int64_t counts[6];
    for (int i = 0; i < 6; i++) counts[i] = qiq_be(at + 20 + i * 4, 4);
    if (data[4] >= '2') {
        // Skip the 32-bit data to the 64-bit header.
        size_t skip = 44 + (size_t)(counts[3] * 5 + counts[4] * 6 + counts[5] + counts[2] * 8 + counts[1] + counts[0]);
        if (skip + 44 > length) return false;
        at = data + skip;
        for (int i = 0; i < 6; i++) counts[i] = qiq_be(at + 20 + i * 4, 4);
        size = 8;
    }
    int64_t isut = counts[0], isstd = counts[1], leap = counts[2], timecnt = counts[3], typecnt = counts[4], charcnt = counts[5];
    if (typecnt < 1 || typecnt > 255 || timecnt < 0 || charcnt < 0) return false;
    size_t needed = 44 + (size_t)(timecnt * size + timecnt + typecnt * 6 + charcnt + leap * (size + 4) + isstd + isut);
    if ((size_t)(at - data) + needed > length) return false;
    const unsigned char *times = at + 44;
    const unsigned char *indexes = times + timecnt * size;
    const unsigned char *types = indexes + timecnt;
    const char *chars = (const char *)(types + typecnt * 6);
    zone->count = (size_t)timecnt;
    zone->times = qiq_zone_alloc(zone->count, sizeof(int64_t));
    zone->indexes = qiq_zone_alloc(zone->count, 1);
    for (int64_t i = 0; i < timecnt; i++) {
        zone->times[i] = qiq_be(times + i * size, size);
        zone->indexes[i] = indexes[i] < typecnt ? indexes[i] : 0;
    }
    zone->type_count = (size_t)typecnt;
    zone->types = qiq_zone_alloc(zone->type_count, sizeof(QiqZoneType));
    for (int64_t i = 0; i < typecnt; i++) {
        const unsigned char *type = types + i * 6;
        zone->types[i].offset = (int32_t)qiq_be(type, 4);
        zone->types[i].dst = type[4] != 0;
        size_t abbreviation = type[5] < charcnt ? type[5] : 0;
        snprintf(zone->types[i].abbreviation, sizeof zone->types[i].abbreviation, "%.*s", (int)(charcnt - (int64_t)abbreviation),
                 chars + abbreviation);
    }
    zone->initial = 0;
    if (size == 8) {
        // The footer: "\n<rule>\n" after the data.
        const char *footer = (const char *)at + needed;
        const char *end = (const char *)data + length;
        if (footer < end && *footer == '\n') {
            const char *close = memchr(footer + 1, '\n', (size_t)(end - footer - 1));
            if (close != NULL) {
                char rule[128];
                snprintf(rule, sizeof rule, "%.*s", (int)(close - footer - 1), footer + 1);
                qiq_parse_rule(rule, &zone->rule);
            }
        }
    }
    return true;
}

static bool qiq_read_file(const char *path, unsigned char **data, size_t *length) {
    FILE *file = fopen(path, "rb");
    if (file == NULL) return false;
    size_t capacity = 4096, used = 0;
    unsigned char *buffer = malloc(capacity);
    if (buffer == NULL) qiq_fatal("out of memory");
    for (;;) {
        if (used == capacity) {
            capacity *= 2;
            if (capacity > (1 << 22)) break; // no zone file is this big
            buffer = realloc(buffer, capacity);
            if (buffer == NULL) qiq_fatal("out of memory");
        }
        size_t got = fread(buffer + used, 1, capacity - used, file);
        if (got == 0) break;
        used += got;
    }
    fclose(file);
    *data = buffer;
    *length = used;
    return true;
}

// The embedded database: see vendor/make_tzdata.py for the format.
typedef struct {
    const unsigned char *at, *end;
} QiqTzReader;

static bool qiq_tz_leb(QiqTzReader *reader, uint64_t *out) {
    uint64_t value = 0;
    for (int shift = 0; reader->at < reader->end && shift < 64; shift += 7) {
        unsigned char byte = *reader->at++;
        value |= (uint64_t)(byte & 0x7f) << shift;
        if (!(byte & 0x80)) {
            *out = value;
            return true;
        }
    }
    return false;
}

static bool qiq_tz_zigzag(QiqTzReader *reader, int64_t *out) {
    uint64_t value;
    if (!qiq_tz_leb(reader, &value)) return false;
    *out = (int64_t)(value >> 1) ^ -(int64_t)(value & 1);
    return true;
}

static const char *qiq_tz_string(QiqTzReader *reader) {
    const unsigned char *start = reader->at;
    while (reader->at < reader->end && *reader->at != 0) reader->at++;
    if (reader->at == reader->end) return NULL;
    reader->at++;
    return (const char *)start;
}

static bool qiq_load_embedded(QiqZone *zone, const char *name) {
    QiqTzReader reader = {qiq_tzdata, qiq_tzdata + sizeof qiq_tzdata};
    if (sizeof qiq_tzdata < 8 || memcmp(qiq_tzdata, "QIQTZ1\n", 7) != 0) return false;
    // After the magic, the version line.
    const unsigned char *version_end = memchr(qiq_tzdata + 7, '\n', sizeof qiq_tzdata - 7);
    if (version_end == NULL) return false;
    reader.at = version_end + 1;
    uint64_t zones, record = UINT64_MAX;
    if (!qiq_tz_leb(&reader, &zones)) return false;
    for (uint64_t i = 0; i < zones; i++) {
        const char *entry = qiq_tz_string(&reader);
        uint64_t number;
        if (entry == NULL || !qiq_tz_leb(&reader, &number)) return false;
        if (strcmp(entry, name) == 0) record = number;
    }
    uint64_t records;
    if (record == UINT64_MAX || !qiq_tz_leb(&reader, &records) || record >= records) return false;
    for (uint64_t i = 0;; i++) {
        uint64_t type_count, initial, count;
        if (!qiq_tz_leb(&reader, &type_count) || type_count == 0 || type_count > 255) return false;
        QiqZoneType *types = qiq_zone_alloc(type_count, sizeof(QiqZoneType));
        for (uint64_t t = 0; t < type_count; t++) {
            int64_t offset;
            const char *abbreviation;
            if (!qiq_tz_zigzag(&reader, &offset) || reader.at >= reader.end) {
                free(types);
                return false;
            }
            types[t].offset = (int32_t)offset;
            types[t].dst = *reader.at++ != 0;
            if ((abbreviation = qiq_tz_string(&reader)) == NULL) {
                free(types);
                return false;
            }
            snprintf(types[t].abbreviation, sizeof types[t].abbreviation, "%s", abbreviation);
        }
        if (!qiq_tz_leb(&reader, &initial) || !qiq_tz_leb(&reader, &count) || initial >= type_count) {
            free(types);
            return false;
        }
        int64_t *times = qiq_zone_alloc(count, sizeof(int64_t));
        for (uint64_t t = 0; t < count; t++) {
            int64_t value;
            uint64_t delta;
            bool ok = t == 0 ? qiq_tz_zigzag(&reader, &value) : qiq_tz_leb(&reader, &delta);
            if (!ok) {
                free(types);
                free(times);
                return false;
            }
            times[t] = t == 0 ? value : times[t - 1] + (int64_t)delta;
        }
        if ((uint64_t)(reader.end - reader.at) < count) {
            free(types);
            free(times);
            return false;
        }
        const unsigned char *indexes = reader.at;
        reader.at += count;
        const char *rule = qiq_tz_string(&reader);
        if (rule == NULL) {
            free(types);
            free(times);
            return false;
        }
        if (i < record) {
            free(types);
            free(times);
            continue;
        }
        zone->types = types;
        zone->type_count = (size_t)type_count;
        zone->initial = (size_t)initial;
        zone->times = times;
        zone->count = (size_t)count;
        zone->indexes = qiq_zone_alloc(count, 1);
        for (uint64_t t = 0; t < count; t++) zone->indexes[t] = indexes[t] < type_count ? indexes[t] : 0;
        qiq_parse_rule(rule, &zone->rule);
        return true;
    }
}

static const char *const qiq_zoneinfo_directories[] = {"/usr/share/zoneinfo/", "/share/zoneinfo/", "/etc/zoneinfo/"};

// A zone name that can only be a file in a zoneinfo directory: letters,
// digits, and -+_/, no "..", not starting with "/".
static bool qiq_zone_name_is_safe(const char *name) {
    if (name[0] == '\0' || name[0] == '/' || strstr(name, "..") != NULL || strlen(name) > 200) return false;
    for (const char *c = name; *c; c++) {
        if (!((*c >= 'a' && *c <= 'z') || (*c >= 'A' && *c <= 'Z') || (*c >= '0' && *c <= '9') || strchr("-+_/", *c))) return false;
    }
    return true;
}

// "+05:30", "-08", "+0530": a fixed offset, written back as "+05:30".
static bool qiq_fixed_offset(const char *name, int32_t *offset, char *canonical, size_t size) {
    if (name[0] != '+' && name[0] != '-') return false;
    const char *c = name + 1;
    int digits[4], count = 0;
    while (*c != '\0' && count < 4) {
        if (*c == ':' && count == 2) {
            c++;
            continue;
        }
        if (*c < '0' || *c > '9') return false;
        digits[count++] = *c++ - '0';
    }
    if (*c != '\0' || (count != 2 && count != 4)) return false;
    int hours = digits[0] * 10 + digits[1], minutes = count == 4 ? digits[2] * 10 + digits[3] : 0;
    if (hours > 18 || minutes > 59) return false;
    *offset = (name[0] == '-' ? -1 : 1) * (hours * 3600 + minutes * 60);
    snprintf(canonical, size, "%c%02d:%02d", *offset < 0 ? '-' : '+', hours, minutes);
    return true;
}

const QiqZone *qiq_zone_find(const char *name) {
    if (name == NULL) return NULL;
    // UTC, and fixed offsets, under one name each.
    int32_t offset;
    char canonical[16];
    bool fixed = qiq_fixed_offset(name, &offset, canonical, sizeof canonical);
    if (strcmp(name, "Z") == 0) name = "UTC";
    if (fixed) name = canonical;
    for (QiqZone *zone = qiq_zones; zone != NULL; zone = zone->next) {
        if (strcmp(zone->name, name) == 0) return zone;
    }
    QiqZone *zone = NULL;
    if (strcmp(name, "UTC") == 0) {
        zone = qiq_new_zone(name);
        zone->types = qiq_zone_alloc(1, sizeof(QiqZoneType));
        zone->type_count = 1;
        snprintf(zone->types[0].abbreviation, sizeof zone->types[0].abbreviation, "UTC");
    } else if (fixed) {
        zone = qiq_new_zone(name);
        zone->types = qiq_zone_alloc(1, sizeof(QiqZoneType));
        zone->type_count = 1;
        zone->types[0].offset = offset;
        snprintf(zone->types[0].abbreviation, sizeof zone->types[0].abbreviation, "%s", canonical);
    } else {
        bool path = strcmp(name, "/etc/localtime") == 0;
        if (!path && !qiq_zone_name_is_safe(name)) return NULL;
        zone = qiq_new_zone(name);
        bool loaded = false;
        for (size_t i = 0; !loaded && i < (path ? 1 : sizeof qiq_zoneinfo_directories / sizeof *qiq_zoneinfo_directories); i++) {
            char file[512];
            snprintf(file, sizeof file, "%s%s", path ? "" : qiq_zoneinfo_directories[i], name);
            unsigned char *data;
            size_t length;
            if (qiq_read_file(file, &data, &length)) {
                loaded = qiq_load_tzif(zone, data, length);
                free(data);
            }
        }
        if (!loaded && !path) loaded = qiq_load_embedded(zone, name);
        if (!loaded) {
            qiq_free_zone(zone);
            return NULL;
        }
    }
    zone->next = qiq_zones;
    qiq_zones = zone;
    return zone;
}

// ---------------------------------------------------------------------------
// Offsets

static const QiqZoneType *qiq_zone_type_at(const QiqZone *zone, int64_t when) {
    if (zone->count == 0 || when < zone->times[0]) {
        if (zone->count == 0 && zone->rule.present) return qiq_rule_at(&zone->rule, when);
        return &zone->types[zone->initial];
    }
    if (when >= zone->times[zone->count - 1] && zone->rule.present) {
        return qiq_rule_at(&zone->rule, when);
    }
    // The last transition at or before `when`.
    size_t low = 0, high = zone->count;
    while (high - low > 1) {
        size_t middle = low + (high - low) / 2;
        if (zone->times[middle] <= when) low = middle;
        else high = middle;
    }
    return &zone->types[zone->indexes[low]];
}

int32_t qiq_zone_offset(const QiqZone *zone, int64_t when, bool *dst, const char **abbreviation) {
    const QiqZoneType *type = qiq_zone_type_at(zone, when);
    if (dst != NULL) *dst = type->dst;
    if (abbreviation != NULL) *abbreviation = type->abbreviation;
    return type->offset;
}

const char *qiq_zone_name_of(const QiqZone *zone) {
    return zone->name;
}

// The UTC time of a wall clock time in `zone` (written as if it were UTC),
// as PHP resolves it: a time skipped by a change to daylight saving time
// moves forward by the change (02:30 becomes 03:30), and a time that happens
// twice, when the clocks go back, is the one with offset `prefer` when that
// is one of them, and otherwise the second (in standard time), as PHP's
// constructor and setTime choose.
int64_t qiq_zone_local_to_utc(const QiqZone *zone, int64_t local, int32_t prefer) {
    // The offsets before and after any change near this time.
    int32_t before = qiq_zone_offset(zone, local - 86400, NULL, NULL);
    int32_t after = qiq_zone_offset(zone, local + 86400, NULL, NULL);
    int64_t with_before = local - before, with_after = local - after;
    bool before_fits = qiq_zone_offset(zone, with_before, NULL, NULL) == before;
    bool after_fits = qiq_zone_offset(zone, with_after, NULL, NULL) == after;
    if (before_fits && after_fits && before != after) {
        if (before == prefer) return with_before;
        if (after == prefer) return with_after;
        return with_before > with_after ? with_before : with_after;
    }
    if (before_fits) return with_before;
    if (after_fits) return with_after;
    // Skipped: read with the offset from before the change, which lands
    // the same distance past it.
    return with_before;
}

// ---------------------------------------------------------------------------
// The default zone: date_default_timezone_set's, or the TZ environment
// variable's, or the system's (/etc/localtime), or UTC.

const char *qiq_default_zone_name(void) {
    static char name[256];
    const char *set = qiq_time_default_zone(); // time.c: date_default_timezone_set's zone
    if (set != NULL && qiq_zone_find(set) != NULL) return set;
    const char *environment = getenv("TZ");
    if (environment != NULL && *environment != '\0') {
        if (*environment == ':') environment++;
        if (qiq_zone_find(environment) != NULL) return environment;
    }
    // /etc/localtime is usually a link to the zone's file in a zoneinfo directory.
    char target[256];
    ssize_t length = readlink("/etc/localtime", target, sizeof target - 1);
    if (length > 0) {
        target[length] = '\0';
        const char *zone = strstr(target, "zoneinfo/");
        if (zone != NULL && qiq_zone_find(zone + 9) != NULL) {
            snprintf(name, sizeof name, "%s", zone + 9);
            return name;
        }
    }
    if (access("/etc/localtime", R_OK) == 0 && qiq_zone_find("/etc/localtime") != NULL) return "/etc/localtime";
    return "UTC";
}
